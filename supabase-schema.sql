-- Lost & Found Management Platform
-- Supabase PostgreSQL schema
-- Run this in Supabase Dashboard -> SQL Editor.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(trim(full_name)) >= 2),
  email text not null unique,
  password_hash text not null,
  role text not null default 'student' check (role in ('admin','staff','student')),
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.found_items (
  id bigint generated by default as identity primary key,
  item_name text not null,
  description text not null,
  category text not null,
  location_found text not null,
  date_found date not null,
  status text not null default 'found' check (status in ('found','claimed','unfound')),
  item_source text not null default 'found' check (item_source in ('found','lost')),
  image_path text,
  found_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lost_reports (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  item_name text not null,
  description text not null,
  category text not null,
  last_seen_location text not null,
  date_lost date not null,
  contact_info text not null,
  image_path text,
  status text not null default 'open' check (status in ('open','matched','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.claims (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.found_items(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  message text not null,
  proof_image_path text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by bigint references public.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_found_items_status on public.found_items(status);
create index if not exists idx_found_items_category on public.found_items(category);
create index if not exists idx_found_items_date on public.found_items(date_found);
create index if not exists idx_lost_reports_user on public.lost_reports(user_id);
create index if not exists idx_lost_reports_status on public.lost_reports(status);
create index if not exists idx_claims_status on public.claims(status);
create index if not exists idx_claims_item on public.claims(item_id);
create index if not exists idx_claims_user on public.claims(user_id);
create index if not exists idx_notifications_user on public.notifications(user_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_users_updated_at on public.users;
create trigger trg_users_updated_at
before update on public.users
for each row execute function public.set_updated_at();

drop trigger if exists trg_found_items_updated_at on public.found_items;
create trigger trg_found_items_updated_at
before update on public.found_items
for each row execute function public.set_updated_at();

drop trigger if exists trg_lost_reports_updated_at on public.lost_reports;
create trigger trg_lost_reports_updated_at
before update on public.lost_reports
for each row execute function public.set_updated_at();

-- Atomic lost-report review workflow.
create or replace function public.review_lost_report(
  p_report_id bigint,
  p_decision text,
  p_reviewer_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  report_row public.lost_reports%rowtype;
  new_item_id bigint;
begin
  if p_decision not in ('approved','rejected') then
    raise exception 'Invalid lost-report decision.';
  end if;

  select * into report_row
  from public.lost_reports
  where id = p_report_id
  for update;

  if not found then
    raise exception 'Lost report not found.';
  end if;

  if report_row.status <> 'open' then
    raise exception 'This lost report has already been reviewed.';
  end if;

  if p_decision = 'approved' then
    insert into public.found_items
      (item_name, description, category, location_found, date_found, status, item_source, image_path, found_by)
    values
      (report_row.item_name, report_row.description, report_row.category,
       report_row.last_seen_location, report_row.date_lost, 'unfound', 'lost',
       report_row.image_path, p_reviewer_id)
    returning id into new_item_id;

    update public.lost_reports
    set status = 'matched', updated_at = now()
    where id = p_report_id;

    insert into public.notifications(user_id, title, message)
    values (
      report_row.user_id,
      'Lost report approved',
      'Your lost-item report was approved and posted as Unfound. Staff can mark it Found when it is recovered.'
    );

    return jsonb_build_object(
      'decision', p_decision,
      'found_item_id', new_item_id,
      'deleted_image_path', null
    );
  end if;

  insert into public.notifications(user_id, title, message)
  values (
    report_row.user_id,
    'Lost report rejected',
    'Your lost-item report was rejected and removed from the system.'
  );

  delete from public.lost_reports where id = p_report_id;

  return jsonb_build_object(
    'decision', p_decision,
    'found_item_id', null,
    'deleted_image_path', report_row.image_path
  );
end;
$$;

-- Atomic claim review workflow.
create or replace function public.review_claim(
  p_claim_id bigint,
  p_status text,
  p_reviewer_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  claim_row public.claims%rowtype;
  item_status text;
begin
  if p_status not in ('approved','rejected') then
    raise exception 'Invalid claim status.';
  end if;

  select * into claim_row
  from public.claims
  where id = p_claim_id
  for update;

  if not found then
    raise exception 'Claim not found.';
  end if;

  if claim_row.status <> 'pending' then
    raise exception 'This claim has already been reviewed.';
  end if;

  select status into item_status
  from public.found_items
  where id = claim_row.item_id
  for update;

  if not found then
    raise exception 'The claimed item no longer exists.';
  end if;

  update public.claims
  set status = p_status, reviewed_by = p_reviewer_id, reviewed_at = now()
  where id = p_claim_id;

  if p_status = 'approved' then
    if item_status <> 'found' then
      raise exception 'This item is no longer available for claiming.';
    end if;

    update public.found_items
    set status = 'claimed', updated_at = now()
    where id = claim_row.item_id;

    insert into public.notifications(user_id, title, message)
    values (
      claim_row.user_id,
      'Claim approved',
      'Your claim was approved. Please coordinate the handover with staff.'
    );
  else
    insert into public.notifications(user_id, title, message)
    values (
      claim_row.user_id,
      'Claim update',
      'Your claim was reviewed and rejected. You may contact staff for details.'
    );
  end if;

  return jsonb_build_object('claim_id', claim_row.id, 'status', p_status);
end;
$$;

-- Allow the backend service role to call these functions.
revoke all on function public.review_lost_report(bigint, text, bigint) from public;
revoke all on function public.review_lost_report(bigint, text, bigint) from anon;
revoke all on function public.review_lost_report(bigint, text, bigint) from authenticated;
grant execute on function public.review_lost_report(bigint, text, bigint) to service_role;

revoke all on function public.review_claim(bigint, text, bigint) from public;
revoke all on function public.review_claim(bigint, text, bigint) from anon;
revoke all on function public.review_claim(bigint, text, bigint) from authenticated;
grant execute on function public.review_claim(bigint, text, bigint) to service_role;

-- Row Level Security is enabled so the anonymous/public API key cannot freely read/write app data.
-- The Node/Express backend uses the Supabase service-role key and therefore bypasses RLS.
alter table public.users enable row level security;
alter table public.found_items enable row level security;
alter table public.lost_reports enable row level security;
alter table public.claims enable row level security;
alter table public.notifications enable row level security;

